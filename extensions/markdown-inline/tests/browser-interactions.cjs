const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const path = require('node:path');
const assert = require('node:assert/strict');
const { webviewPage } = require('./browser-webview.cjs');
const { output, html } = webviewPage('interactions');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_BIN, headless: true, args: ['--allow-file-access-from-files'] });
  try {
    const page = await browser.newPage();
    const errors = [], messages = [];
    page.on('pageerror', error => errors.push(error.stack));
    let text = '# Heading\n\nA [link](./guide.md) here.\n\n| Name | Value |\n| --- | --- |\n| [table link](./table.md) | cell |\n\n```js\nexample()\n```\n';
    let version = 1;
    await page.exposeFunction('bridge', async message => {
      messages.push(message);
      if (message.type === 'ready') await page.evaluate(m => window.postMessage(m, '*'), { type: 'update', text, version, dirty: false });
      if (message.type === 'edit') {
        assert.equal(message.version, version);
        text = message.text; version++;
        await page.evaluate(m => window.postMessage(m, '*'), { type: 'editResult', status: 'applied', requestId: message.requestId, text, version, dirty: true });
      }
    });
    await page.addInitScript(() => { window.acquireVsCodeApi = () => ({ postMessage: m => window.bridge(m), getState: () => null, setState: () => {} }); });
    await page.goto('file://' + output);
    await page.waitForSelector('.ProseMirror');
    const panel = page.locator('.milkdown-link-tooltip');
    const link = page.locator('.ProseMirror a').first();
    await link.hover();
    await page.waitForTimeout(400);
    assert.equal(await panel.getAttribute('data-mode'), 'preview');
    await panel.hover();
    await page.waitForTimeout(200);
    assert.equal(await panel.isVisible(), true);
    await page.keyboard.press('Escape');
    await page.waitForTimeout(150);
    assert.equal(await panel.isVisible(), false);
    await page.locator('.ProseMirror h1').click();
    await link.click({ modifiers: ['Shift'] });
    await page.waitForTimeout(100);
    assert.equal(messages.at(-1).type, 'openLink');
    assert.equal(messages.at(-1).href, './guide.md');
    await link.click();
    const input = page.getByRole('textbox', { name: 'Link destination' });
    await input.fill('./draft.md');
    await page.evaluate(() => window.dispatchEvent(new Event('resize')));
    await page.waitForTimeout(150);
    assert.equal(await input.inputValue(), './draft.md');
    await page.keyboard.press('Escape');
    await page.waitForTimeout(250);
    assert.equal(await panel.isVisible(), false);
    await page.keyboard.type('x');
    await page.waitForTimeout(350);
    assert.equal(await panel.isVisible(), false, 'typing linked text does not reopen the form');
    await link.click();
    await input.fill('./updated.md');
    await input.press('Enter');
    await page.waitForTimeout(350);
    assert.ok(text.includes('./updated.md'));
    assert.equal(await panel.isVisible(), false);
    await page.locator('.ProseMirror td a').click();
    assert.equal(await input.inputValue(), './table.md');
    await page.getByRole('button', { name: 'Close', exact: true }).click();
    await page.waitForTimeout(250);
    assert.equal(await panel.isVisible(), false);
    await page.locator('.ProseMirror h1').click();
    await page.evaluate(() => window.postMessage({ type: 'command', command: 'addLink' }, '*'));
    await input.waitFor({ state: 'visible' });
    await input.fill('#heading');
    await input.press('Enter');
    await page.waitForTimeout(350);
    assert.ok(text.includes('#heading'));
    await page.evaluate(() => window.postMessage({ type: 'navigateHeading', fragment: 'headingheading' }, '*'));
    await page.waitForTimeout(150);
    assert.equal(await page.evaluate(() => getSelection().anchorNode.parentElement.closest('h1')?.textContent), 'Heading#heading');
    await page.evaluate(() => window.postMessage({ type: 'navigateHeading', fragment: 'absent' }, '*'));
    await page.waitForTimeout(100);
    assert.ok((await page.locator('#save-state').innerText()).includes('Heading not found'));
    await page.locator('.ProseMirror h1').click();
    await page.keyboard.press('Alt+F10');
    await page.waitForTimeout(100);
    assert.equal(await page.evaluate(() => document.activeElement?.closest('[role="toolbar"]')?.getAttribute('aria-label')), 'Formatting and block actions');
    await page.keyboard.press('End');
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Move block down');
    await page.keyboard.press('Escape');
    await page.locator('.ProseMirror td').last().click();
    await page.keyboard.press('Alt+F10');
    await page.waitForTimeout(100);
    assert.equal(await page.evaluate(() => document.activeElement?.closest('[role="toolbar"]')?.getAttribute('aria-label')), 'Table actions');
    await page.keyboard.press('End');
    await page.keyboard.press('Home');
    await page.keyboard.press('Escape');
    await page.locator('.ProseMirror h1').click();
    await page.evaluate(() => window.postMessage({type: 'command', command: 'moveBlockDown'}, '*'));
    await page.waitForTimeout(350);
    assert.ok(text.indexOf('A [') < text.indexOf('# Heading'));
    await page.evaluate(() => window.postMessage({type: 'command', command: 'moveBlockUp'}, '*'));
    await page.waitForTimeout(350);
    assert.ok(text.startsWith('# Heading'));
    const language = page.getByRole('button', { name: 'Code language', exact: true });
    await language.focus(); await page.keyboard.press('Enter');
    await page.getByRole('textbox', { name: 'Search languages' }).fill('python');
    await page.keyboard.press('ArrowDown'); await page.keyboard.press('Space');
    await page.waitForTimeout(350);
    assert.ok(text.includes('```python'));
    await language.press('Enter');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.code-lang-dropdown').evaluate(el => el.inert), true);
    await language.press('Enter');
    await page.waitForTimeout(150);
    assert.equal(await page.locator('.code-lang-dropdown').isVisible(), true);
    await page.keyboard.press('Escape');
    for (const width of [320, 480, 768, 1440]) {
      await page.setViewportSize({ width, height: 700 });
      await language.click();
      const box = await page.locator('.code-lang-dropdown').boundingBox();
      assert.ok(box.x >= 0 && box.x + box.width <= width, 'menu stays in viewport');
      await page.keyboard.press('Escape');
    }
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await language.click();
    assert.equal(await page.locator('.code-lang-dropdown').evaluate(el => getComputedStyle(el).transitionDuration), '0s');
    await page.keyboard.press('Escape');
    await page.getByRole('button', {name: 'Add metadata', exact: true}).click();
    await page.getByRole('button', {name: 'YAML', exact: true}).click();
    const yaml = page.getByRole('textbox', {name: 'Front matter YAML source'});
    await yaml.fill('title: "One"\nsecond: "Two"\n');
    await page.getByRole('button', {name: 'Fields', exact: true}).click();
    const firstField = page.getByRole('textbox', {name: 'title (string)'});
    await firstField.fill('Changed');
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Remove field title');
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'second (string)');
    if (await page.locator('#frontmatter-toggle').getAttribute('aria-expanded') === 'false') await page.locator('#frontmatter-toggle').click();
    await page.getByRole('button', {name: 'YAML', exact: true}).click();
    await yaml.fill('title: "One"\ntitle: "Duplicate"\n');
    await page.locator('#frontmatter-toggle').click();
    assert.equal(await page.locator('.frontmatter-error').isVisible(), true);
    assert.equal(await page.locator('.frontmatter-source').isVisible(), false);
    if (await page.locator('#frontmatter-toggle').getAttribute('aria-expanded') === 'false') await page.locator('#frontmatter-toggle').click();
    await page.getByRole('button', {name: 'YAML', exact: true}).click();
    await yaml.fill('title: "One"\nsecond: "Two"\n');
    for (const width of [320, 480, 768, 1440]) {
      await page.setViewportSize({width, height: 700});
      const before = await page.locator('header').boundingBox();
      assert.equal(await page.locator('#copy-document, #copy-path, #copy-folder-path').count(), 0);
      await page.locator('#inline-theme').hover();
      const after = await page.locator('header').boundingBox();
      assert.deepEqual(after, before, 'header hover does not change geometry');
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    }
    const beforeRemoval = text;
    for (const mode of ['Fields', 'YAML']) {
      await page.getByRole('button', {name: mode, exact: true}).click();
      await page.locator('.metadata-remove').click();
      assert.ok((await page.locator('.metadata-confirm').textContent()).includes('Remove all metadata?'));
      assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Cancel');
      await page.keyboard.press('Escape');
      assert.equal(text, beforeRemoval, 'Escape retains all metadata in ' + mode);
      await page.locator('.metadata-remove').click();
      await page.locator('.metadata-confirm').getByRole('button', {name:'Cancel',exact:true}).click();
      assert.equal(text, beforeRemoval, 'Cancel retains all metadata in ' + mode);
    }
    await page.locator('.metadata-remove').click();
    await page.locator('.metadata-confirm-remove').click();
    await page.waitForTimeout(350);
    assert.ok(!text.startsWith('---'));
    await page.locator('.ProseMirror h1').click();
    await page.keyboard.press('End');
    await page.evaluate(() => {
      const data = new DataTransfer(); data.setData('text/plain', '**BOLD**'); data.setData('text/html', '<span>**BOLD**</span>'); data.setData('vscode-editor-data', '{"mode":"markdown"}');
      document.querySelector('.ProseMirror').dispatchEvent(new ClipboardEvent('paste', {clipboardData: data, bubbles: true, cancelable: true}));
    });
    await page.waitForTimeout(350);
    assert.ok(await page.locator('.ProseMirror strong').filter({hasText:'BOLD'}).count());
    await page.evaluate(() => window.postMessage({type: 'pasteText', text: '**LITERAL**'}, '*'));
    await page.waitForTimeout(350);
    assert.ok((await page.locator('.ProseMirror').innerText()).includes('**LITERAL**'));
    await page.locator('.code-lang-wrapper code').click();
    await page.keyboard.press('End');
    await page.waitForTimeout(100);
    await page.evaluate(() => {
      const data = new DataTransfer(); data.setData('text/plain', '**CODE**'); data.setData('text/html', '<b>CODE</b>');
      document.querySelector('.ProseMirror').dispatchEvent(new ClipboardEvent('paste', {clipboardData:data, bubbles:true, cancelable:true}));
    });
    await page.waitForTimeout(350);
    assert.ok((await page.locator('.code-lang-wrapper code').innerText()).includes('**CODE**'), JSON.stringify({text, body:await page.locator('.ProseMirror').innerText(), errors}));
    await page.locator('#open-raw').click();
    await page.waitForTimeout(100);
    const sourceMessage = messages.filter(message => message.type === 'openRaw').at(-1);
    assert.equal(sourceMessage.offset, text.indexOf('```python'));
    await page.evaluate(offset => window.postMessage({type: 'navigateSource', offset}, '*'), sourceMessage.offset);
    await page.waitForTimeout(100);
    assert.ok(await page.evaluate(() => getSelection().anchorNode.parentElement.closest('code')));
    await page.keyboard.insertText(' café 日本語');
    await page.waitForTimeout(350);
    assert.ok(text.includes('café 日本語'));
    await page.emulateMedia({ forcedColors: 'active' });
    await page.evaluate(() => { document.documentElement.dataset.inlineTheme='auto'; document.body.className='vscode-high-contrast'; });
    await page.locator('.code-lang-trigger').focus();
    assert.ok((await page.locator('body').ariaSnapshot()).includes('Code language'));
    await page.screenshot({path:path.join(process.env.MARKDOWN_INLINE_TEST_ROOT,'interactions-high-contrast.png')});
    await page.emulateMedia({ forcedColors: 'none' });
    await page.evaluate(() => { document.documentElement.dataset.inlineTheme='light'; });
    await page.setViewportSize({width:480,height:800});
    await page.screenshot({path:path.join(process.env.MARKDOWN_INLINE_TEST_ROOT,'interactions-480.png')});
    assert.deepEqual(errors, []);
    assert.ok(messages.some(m => m.type === 'edit'));
    console.log('PASS intentional link editing, draft retention, dismissal, typing and table links');
    await page.close();
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
